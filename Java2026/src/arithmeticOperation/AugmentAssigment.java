package arithmeticOperation;

public class AugmentAssigment {

    public static void main(String[] args) {
        int x = 10;
        int y = 5;

        // Augmented Assignment Operator
            x += y; // x = x + y
            x -= y; // x = x - y
            x *= y; // x = x * y
            x /= y; // x = x / y
            x %= y; // x = x % y

        System.out.println(x);

    }
}
