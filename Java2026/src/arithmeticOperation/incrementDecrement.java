package arithmeticOperation;

/* Increment and Decrement Operators for looping structures
    int x = 1;
    x = x + 1;
    x += 1;
    x++
    x--
* */

public class incrementDecrement {

    public static  void main(String[] args) {

       int x = 1;

       //increment x by 1
       x ++;

        //decrement x by 1
        x --;


        System.out.println(x);
    }
}
